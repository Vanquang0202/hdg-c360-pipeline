-- Template only. Invoke-OracleSetup.ps1 supplies the password in memory.
-- Execute as SYSDBA in CDB$ROOT after checking USERS tablespace in both containers.
-- Intentionally fail if this common user already exists; do not replace its password.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET ECHO OFF
SET VERIFY OFF
SET DEFINE OFF
ALTER SESSION SET CONTAINER=CDB$ROOT;
CREATE USER C##HDG_CDC IDENTIFIED BY "__CDC_PASSWORD__"
  DEFAULT TABLESPACE USERS QUOTA 100M ON USERS CONTAINER=ALL;
GRANT CREATE SESSION, SET CONTAINER, LOGMINING, SELECT ANY TRANSACTION,
  CREATE TABLE, CREATE SEQUENCE, LOCK ANY TABLE TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT_CATALOG_ROLE, EXECUTE_CATALOG_ROLE TO C##HDG_CDC CONTAINER=ALL;
GRANT EXECUTE ON SYS.DBMS_LOGMNR TO C##HDG_CDC CONTAINER=ALL;
GRANT EXECUTE ON SYS.DBMS_LOGMNR_D TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$DATABASE TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$LOG TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$LOG_HISTORY TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$LOGMNR_LOGS TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$LOGMNR_CONTENTS TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$LOGMNR_PARAMETERS TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$LOGFILE TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$ARCHIVED_LOG TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$ARCHIVE_DEST_STATUS TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$TRANSACTION TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$MYSTAT TO C##HDG_CDC CONTAINER=ALL;
GRANT SELECT ON SYS.V_$STATNAME TO C##HDG_CDC CONTAINER=ALL;
ALTER SESSION SET CONTAINER=FREEPDB1;
ALTER USER C##HDG_CDC QUOTA 100M ON USERS;
GRANT SELECT, FLASHBACK ON VSS.VSS_HO_GD_NHANKHAU TO C##HDG_CDC;
GRANT SELECT, FLASHBACK ON VSS.VSS_DM_DANTOC TO C##HDG_CDC;
GRANT SELECT, FLASHBACK ON VSS.VSS_DM_QUOC_TICH TO C##HDG_CDC;
GRANT SELECT, FLASHBACK ON VSS.VSS_DM_DBHC TO C##HDG_CDC;
EXIT;
