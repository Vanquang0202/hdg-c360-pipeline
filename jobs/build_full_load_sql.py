# Mục đích: Sinh bốn file SQL PostgreSQL từ cùng một hợp đồng Oracle.
# Đầu vào: schema_contract.py, template full_load_guards.sql và phần metadata DDL hiện có.
# Đầu ra: DDL/publisher/migration/candidate SQL; --check chỉ đối chiếu file, không kết nối DB.
"""Generate PostgreSQL assets from the strict Oracle contract. Never connects to a database."""
import argparse
from pathlib import Path
from schema_contract import ROOT, source_schema, pg_catalog_type, checked_expression, byte_constraint

SCHEMA = source_schema()
HEADER = "-- Generated by jobs/build_full_load_sql.py; edit the generator/contract, not this file.\n"


def columns(table, typed=False, compare=False):
    parts = []
    for c in table["columns"]:
        expr = checked_expression(c) if typed else c["name"]
        if compare and c["family"] == "string":
            expr += ' COLLATE "C"'
        parts.append(expr)
    return ", ".join(parts)


def difference(table, namespace="public"):
    mirror = table["mirror"]
    actual = f"SELECT {columns(table, compare=True)} FROM {namespace}.{mirror}"
    stage = f"SELECT {columns(table, typed=True, compare=True)} FROM hdg_stage.{mirror} WHERE load_run_id=p_run_id"
    return f"({actual} EXCEPT ALL {stage}) UNION ALL ({stage} EXCEPT ALL {actual})"


def assertion_sql():
    rows = []
    for t in SCHEMA.values():
        for namespace in ("public","hdg_stage"):
            for i,c in enumerate(t["columns"],1):
                typ = pg_catalog_type(c) if namespace=="public" else "text"
                rows.append(f"('{namespace}','{t['mirror']}',{i},'{c['name']}','{typ}',{str(c['required']).lower()})")
            if namespace=="hdg_stage":
                rows.append(f"('{namespace}','{t['mirror']}',{len(t['columns'])+1},'load_run_id','character varying(36)',true)")
    sql = """
CREATE OR REPLACE FUNCTION hdg_load.assert_mirror_schema()
RETURNS void LANGUAGE plpgsql SET search_path=pg_catalog AS $f$
BEGIN
    IF current_setting('server_encoding') <> 'UTF8' THEN
        RAISE EXCEPTION 'UTF8 PostgreSQL is required for Oracle BYTE contract';
    END IF;
    IF EXISTS (
      WITH expected(ns,tbl,pos,col,typ,nn) AS (VALUES
""" + ",\n".join(rows) + """
      ), actual AS (
        SELECT n.nspname::text ns, c.relname::text tbl, a.attnum::int pos,
               a.attname::text col, format_type(a.atttypid,a.atttypmod) typ, a.attnotnull nn
        FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid
        JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE a.attnum>0 AND NOT a.attisdropped
          AND n.nspname IN ('public','hdg_stage')
          AND c.relname IN ('mirror_hdg_nhankhau','mirror_dm_dantoc','mirror_dm_quoc_tich','mirror_dm_dbhc')
      )
      SELECT 1 FROM expected e FULL JOIN actual a USING(ns,tbl,pos)
      WHERE e.col IS DISTINCT FROM a.col OR e.typ IS DISTINCT FROM a.typ OR e.nn IS DISTINCT FROM a.nn
    ) THEN RAISE EXCEPTION 'Mirror/stage schema differs in column, typmod, nullability or order'; END IF;
"""
    for t in SCHEMA.values():
        for c in t["columns"]:
            if c["family"]=="string" and c["unit"]=="BYTE":
                expr = f"octet_length{c['name']}<={c['length']}"
                sql += f"""
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
        WHERE conrelid='public.{t['mirror']}'::regclass AND conname='{byte_constraint(t,c)}'
          AND contype='c' AND convalidated
          AND replace(regexp_replace(pg_get_expr(conbin,conrelid),'[[:space:]()]','','g'),'::text','')='{expr}') THEN
        RAISE EXCEPTION 'Missing or different BYTE check: {t['mirror']}.{c['name']}';
    END IF;
"""
        if t["primary_key"]:
            sql += f"""
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
       WHERE conrelid='public.{t['mirror']}'::regclass AND contype='p'
         AND pg_get_constraintdef(oid)='PRIMARY KEY (id)') THEN
       RAISE EXCEPTION 'Missing ID primary key for {t['mirror']}';
    END IF;
"""
    return sql + "END $f$;\n"


def digest_sql():
    allowed = ",".join("'" + t["mirror"] + "'" for t in SCHEMA.values())
    return f"""
CREATE OR REPLACE FUNCTION hdg_load.stage_digest(p_table text,p_run_id text)
RETURNS text LANGUAGE plpgsql SET search_path=pg_catalog AS $f$
DECLARE digest text;
BEGIN
    IF p_table NOT IN ({allowed}) THEN RAISE EXCEPTION 'Unknown staging table'; END IF;
    EXECUTE format(
      'SELECT encode(sha256(convert_to(coalesce(string_agg(h, %L ORDER BY h COLLATE "C"), %L),%L)),%L)
       FROM (SELECT encode(sha256(convert_to((to_jsonb(t)-%L)::text,%L)),%L) h
             FROM hdg_stage.%I t WHERE load_run_id=$1) q',
      '', '', 'UTF8', 'hex', 'load_run_id', 'UTF8','hex',p_table)
    INTO digest USING p_run_id;
    RETURN digest;
END $f$;
"""


def stage_validation():
    sql = ""
    for source,t in SCHEMA.items():
        sql += f"""
    SELECT source_rows,stage_digest INTO STRICT expected_count,expected_digest
       FROM hdg_load.table_runs WHERE run_id=p_run_id AND source_table='{source}' AND content_equal;
    SELECT count(*) INTO actual_count FROM hdg_stage.{t['mirror']} WHERE load_run_id=p_run_id;
    IF actual_count<>expected_count OR expected_digest IS NULL OR
       expected_digest IS DISTINCT FROM hdg_load.stage_digest('{t['mirror']}',p_run_id) THEN
        RAISE EXCEPTION 'Stage count/content audit missing or changed for {source}; revalidate against Oracle snapshot';
    END IF;
    PERFORM {columns(t,typed=True)} FROM hdg_stage.{t['mirror']} WHERE load_run_id=p_run_id;
"""
    return sql


def locks():
    return "".join(f"    LOCK TABLE public.{t['mirror']} IN ACCESS EXCLUSIVE MODE;\n" for t in SCHEMA.values()) + "".join(
        f"    LOCK TABLE hdg_stage.{t['mirror']} IN SHARE MODE;\n" for t in SCHEMA.values())


def publish_sql():
    # Sinh publisher có khóa, guard, digest và so toàn dòng; không thực hiện SQL tại đây.
    sql = HEADER+"BEGIN;\n-- Mục đích: cài guard, digest, kiểm schema và publisher Full Load có bảo vệ.\n-- Đầu vào: Stage/run đã đối soát; đầu ra: hàm trả COMMITTED hoặc NOOP, còn lệch thì lỗi.\n"+(ROOT/"jobs/full_load_guards.sql").read_text(encoding="utf-8")
    sql += digest_sql()+assertion_sql()
    sql += """
CREATE OR REPLACE FUNCTION hdg_load.contract_version() RETURNS integer
LANGUAGE sql IMMUTABLE AS 'SELECT 2';
CREATE OR REPLACE FUNCTION hdg_load.publish_full_load(p_run_id varchar)
RETURNS text LANGUAGE plpgsql SET search_path=pg_catalog AS $publish$
DECLARE state hdg_load.control%ROWTYPE; run_status text;
    expected_count bigint; actual_count bigint; expected_digest text; copied boolean:=false;
BEGIN
    -- BƯỚC 1: Khóa control và chặn publish khi CDC đang giữ trách nhiệm cập nhật.
    PERFORM pg_advisory_xact_lock(784027,2);
    SELECT * INTO STRICT state FROM hdg_load.control WHERE id=1 FOR UPDATE;
    IF state.cdc_enabled THEN RAISE EXCEPTION 'CDC enabled; separately verified handoff required'; END IF;
    SELECT status INTO STRICT run_status FROM hdg_load.runs WHERE run_id=p_run_id FOR UPDATE;
    IF run_status<>'VALIDATED' THEN RAISE EXCEPTION 'Run must be VALIDATED'; END IF;
    IF (SELECT count(*) FROM hdg_load.table_runs WHERE run_id=p_run_id AND content_equal AND source_rows=stage_rows)<>4 THEN
        RAISE EXCEPTION 'Four validated table audits required';
    END IF;
""" + locks() + "    PERFORM hdg_load.assert_mirror_schema();\n" + stage_validation()
    sql += "    -- BƯỚC 2: Sau kiểm schema/digest, chỉ nạp bootstrap vào cả bốn Mirror rỗng.\n    IF NOT state.bootstrap_published THEN\n"
    for t in SCHEMA.values():
        sql += f"        IF EXISTS(SELECT 1 FROM public.{t['mirror']}) THEN RAISE EXCEPTION 'Initial publish requires empty Mirror'; END IF;\n"
    for t in SCHEMA.values():
        sql += f"        INSERT INTO public.{t['mirror']} ({columns(t)}) SELECT {columns(t,typed=True)} FROM hdg_stage.{t['mirror']} WHERE load_run_id=p_run_id;\n"
    sql += "        copied:=true;\n    END IF;\n"
    for t in SCHEMA.values():
        sql += f"    IF EXISTS({difference(t)}) THEN RAISE EXCEPTION 'Mirror content differs for {t['mirror']}; publish refused'; END IF;\n"
    return sql+"""
    -- BƯỚC 3: Chỉ sau khi toàn dòng bằng nhau mới xác nhận kết quả; NOOP giữ nguyên dữ liệu.
    UPDATE hdg_load.control SET bootstrap_published=true,
      last_run_id=CASE WHEN copied THEN p_run_id ELSE last_run_id END WHERE id=1;
    UPDATE hdg_load.runs SET status=CASE WHEN copied THEN 'COMMITTED' ELSE 'NOOP' END,
      finished_at=clock_timestamp() WHERE run_id=p_run_id;
    RETURN CASE WHEN copied THEN 'COMMITTED' ELSE 'NOOP' END;
END $publish$;
COMMIT;
"""


def ddl_sql():
    # Control metadata is stable; keep original preamble when regenerating.
    # Sinh Mirror đúng kiểu và Stage text theo cùng hợp đồng; giữ phần metadata đầu file hiện có.
    old=(ROOT/"sql/postgres/01_create_mirror_tables.sql").read_text(encoding="utf-8")
    prefix=old[:old.index("CREATE TABLE public.mirror_hdg_nhankhau")]
    if "stage_digest" not in prefix:
        prefix=prefix.replace("    content_equal boolean NOT NULL,","    content_equal boolean NOT NULL,\n    stage_digest varchar(64),")
    prefix=prefix.removeprefix(HEADER)
    sql=HEADER+prefix
    for t in SCHEMA.values():
        definitions=[]
        for c in t["columns"]:
            definitions.append(f"    {c['name']} {c['postgres']}"+(" NOT NULL" if c["required"] else ""))
        for c in t["columns"]:
            if c["family"]=="string" and c["unit"]=="BYTE":
                definitions.append(f"    CONSTRAINT {byte_constraint(t,c)} CHECK (octet_length({c['name']}) <= {c['length']})")
        if t["primary_key"]:
            definitions.append(f"    CONSTRAINT pk_{t['mirror']} PRIMARY KEY ({','.join(t['primary_key'])})")
        sql+=f"CREATE TABLE public.{t['mirror']} (\n"+",\n".join(definitions)+"\n);\n\n"
        definitions=[f"    {c['name']} text"+(" NOT NULL" if c["required"] else "") for c in t["columns"]]
        definitions.append("    load_run_id varchar(36) NOT NULL REFERENCES hdg_load.runs")
        sql+=f"CREATE TABLE hdg_stage.{t['mirror']} (\n"+",\n".join(definitions)+"\n);\n"
        sql+=f"CREATE INDEX ix_stage_{t['mirror']} ON hdg_stage.{t['mirror']}(load_run_id);\n\n"
    return sql+"CREATE INDEX ix_mirror_hdg_ma_cd ON public.mirror_hdg_nhankhau(ma_cd);\nCOMMIT;\n"


def migration_sql():
    # Sinh migration có kiểm tra trước khi đổi kiểu; mở rộng cột không phục hồi chuỗi đã mất.
    sql=HEADER+"""-- Mục đích: sửa kiểu/constraint và thay publisher trong cùng một transaction.
-- Đầu vào: schema hiện có; đầu ra: contract v2, không tự phục hồi chuỗi đã mất.
-- BƯỚC 1: Lấy khóa, kiểm mọi giá trị trước khi đổi kiểu để tránh mất thông tin.
-- BƯỚC 2: Cập nhật constraint/audit và cài cùng bộ hàm publish, rồi kiểm schema trước commit.
-- Schema only: does not restore previously truncated values.
-- Stop/quiesce all Mirror writers first; do not infer this from cdc_enabled alone.
BEGIN;
SET LOCAL lock_timeout='10s';
SET LOCAL statement_timeout='10min';
SELECT pg_advisory_xact_lock(784027,1);
SELECT pg_advisory_xact_lock(784027,2);
SELECT id FROM hdg_load.control WHERE id=1 FOR UPDATE;
"""
    sql+=locks()
    sql+="ALTER TABLE hdg_load.table_runs ADD COLUMN IF NOT EXISTS stage_digest varchar(64);\n"
    for t in SCHEMA.values():
        for c in t["columns"]:
            n=c["name"]; cond=f"{n} IS NULL" if c["required"] else "false"
            if c["family"]=="string":
                cond+=f" OR char_length({n})>{c['length']}"
                if c["unit"]=="BYTE": cond+=f" OR octet_length({n})>{c['length']}"
                using=f"{n}::text"
            elif c["family"]=="number":
                if c["precision"] is not None:
                    cond+=f" OR {n}<>round({n},{c['scale']}) OR abs({n})>=power(10::numeric,{c['precision']-c['scale']})"
                using=f"{n}::numeric"
            else:
                p=c["temporal_precision"]
                cond+=f" OR {n}<>date_trunc('second',{n})" if p==0 else ""
                using=f"{n}::timestamp without time zone"
            sql+=f"""DO $m$ BEGIN
 IF EXISTS(SELECT 1 FROM public.{t['mirror']} WHERE {cond}) THEN
 RAISE EXCEPTION 'Migration would lose values in {t['mirror']}.{n}'; END IF;
END $m$;
ALTER TABLE public.{t['mirror']} ALTER COLUMN {n} TYPE {c['postgres']} USING {using};
ALTER TABLE public.{t['mirror']} ALTER COLUMN {n} {"SET" if c["required"] else "DROP"} NOT NULL;
"""
        for c in t["columns"]:
            if c["family"]=="string" and c["unit"]=="BYTE":
                ck=byte_constraint(t,c)
                sql+=f"ALTER TABLE public.{t['mirror']} DROP CONSTRAINT IF EXISTS {ck};\n"
                sql+=f"ALTER TABLE public.{t['mirror']} ADD CONSTRAINT {ck} CHECK (octet_length({c['name']})<={c['length']});\n"
    # Replace the obsolete publisher in the SAME transaction as schema migration.
    body=publish_sql().removeprefix(HEADER).removeprefix("BEGIN;\n")
    sql+=body.removesuffix("COMMIT;\n")
    return sql+"SELECT hdg_load.assert_mirror_schema();\nCOMMIT;\n"


def recovery_sql():
    # Sinh hàm dựng candidate riêng, không sinh thao tác ghi đè Mirror live.
    sql=HEADER+"""-- Mục đích: cài hàm dựng candidate cách ly từ Stage đã có audit.
-- Đầu vào: run_id, SCN mong đợi và tên schema hdg_recovery_* mới.
-- Đầu ra: bốn bảng candidate và kiểm toàn dòng; không tự chuyển dữ liệu sang live.
-- BƯỚC 1: Kiểm schema/SCN, giữ Stage ổn định và xác minh digest.
-- BƯỚC 2: Tạo đủ bốn bảng trong schema mới, đối soát hai chiều rồi kết thúc.
-- Builds an isolated candidate only. No live Mirror/control/run status changes.
BEGIN;
CREATE OR REPLACE FUNCTION hdg_load.build_recovery_candidate(p_run_id varchar,p_expected_scn numeric,p_schema text)
RETURNS void LANGUAGE plpgsql SET search_path=pg_catalog AS $f$
DECLARE actual_count bigint; expected_count bigint; expected_digest text;
BEGIN
    IF p_schema !~ '^hdg_recovery_[a-z0-9_]+$' OR length(p_schema)>50 THEN
        RAISE EXCEPTION 'Use an explicit hdg_recovery_* schema, max length 50';
    END IF;
    PERFORM pg_advisory_xact_lock(784027,1);
    PERFORM hdg_load.assert_mirror_schema();
    IF NOT EXISTS(SELECT 1 FROM hdg_load.runs WHERE run_id=p_run_id AND source_scn=p_expected_scn) THEN
        RAISE EXCEPTION 'Run SCN differs from operator-selected recovery snapshot';
    END IF;
"""
    sql+="".join(f"    LOCK TABLE hdg_stage.{t['mirror']} IN SHARE MODE;\n" for t in SCHEMA.values())
    sql+=stage_validation()+"    EXECUTE format('CREATE SCHEMA %I',p_schema);\n"
    for t in SCHEMA.values():
        sql+=f"""    EXECUTE format('CREATE TABLE %I.{t['mirror']} (LIKE public.{t['mirror']} INCLUDING ALL)',p_schema);
    EXECUTE format('INSERT INTO %I.{t['mirror']} ({columns(t)}) SELECT {columns(t,typed=True)} FROM hdg_stage.{t['mirror']} WHERE load_run_id=$1',p_schema) USING p_run_id;
    EXECUTE format('SELECT count(*) FROM ((SELECT {columns(t,compare=True)} FROM %I.{t['mirror']} EXCEPT ALL SELECT {columns(t,typed=True,compare=True)} FROM hdg_stage.{t['mirror']} WHERE load_run_id=$1) UNION ALL (SELECT {columns(t,typed=True,compare=True)} FROM hdg_stage.{t['mirror']} WHERE load_run_id=$1 EXCEPT ALL SELECT {columns(t,compare=True)} FROM %I.{t['mirror']})) d',p_schema,p_schema) INTO actual_count USING p_run_id;
    IF actual_count<>0 THEN RAISE EXCEPTION 'Recovery candidate content mismatch'; END IF;
"""
    # SQL dynamic format strings must escape literal C collation double quotes are fine; no % in expressions.
    return sql+"END $f$;\nCOMMIT;\n"


def generated_files():
    return {
        "sql/postgres/01_create_mirror_tables.sql":ddl_sql(),
        "sql/postgres/02_publish_full_load.sql":publish_sql(),
        "sql/postgres/03_fix_mirror_contract.sql":migration_sql(),
        "sql/postgres/04_build_recovery_candidate.sql":recovery_sql(),
    }


def main():
    # BƯỚC 1: Dựng nội dung SQL từ contract; --check chỉ so sánh, bỏ --check mới ghi lại các file SQL.
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true",help="Check generated assets without writing")
    args=parser.parse_args()
    for path,content in generated_files().items():
        target=ROOT/path
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8")!=content:
                raise SystemExit("Generated SQL is stale: "+path)
        else:
            target.write_text(content,encoding="utf-8")
        print(("Checked " if args.check else "Generated ")+path)


if __name__=="__main__":
    main()
